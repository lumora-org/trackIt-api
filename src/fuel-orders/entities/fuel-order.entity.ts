import { ApiProperty } from '@nestjs/swagger';
import { Column, Entity, Index, JoinColumn, ManyToOne, OneToMany } from 'typeorm';
import { FuelOrderStatus } from '../../common/enums/fuel.enum';
import { BaseEntity, pgEnum } from '../../common/entities/base.entity';
import { Business } from '../../businesses/entities/business.entity';
import { Supplier } from '../../suppliers/entities/supplier.entity';
import { Branch } from '../../branches/entities/branch.entity';
import { User } from '../../users/entities/user.entity';
import { FuelOrderItem } from './fuel-order-item.entity';
import { Delivery } from '../../deliveries/entities/delivery.entity';

@Index('fuel_orders_business_id', ['businessId'])
@Index('fuel_orders_destination_branch_id', ['destinationBranchId'])
@Index('fuel_orders_status', ['status'])
@Index('fuel_orders_business_id_order_number', ['businessId', 'orderNumber'], { unique: true })
@Entity({ name: 'fuel_orders' })
export class FuelOrder extends BaseEntity {
  /** Generated by the backend — the frontend must never supply it (docs/09 §8). */
  @ApiProperty({ example: 'ORD-2026-000001' })
  @Column({ name: 'order_number', type: 'varchar', length: 50 })
  orderNumber!: string;

  @ApiProperty({ format: 'uuid' })
  @Column({ name: 'business_id', type: 'uuid' })
  businessId!: string;

  @ApiProperty({ format: 'uuid' })
  @Column({ name: 'supplier_id', type: 'uuid' })
  supplierId!: string;

  @ApiProperty({ format: 'uuid' })
  @Column({ name: 'destination_branch_id', type: 'uuid' })
  destinationBranchId!: string;

  @ApiProperty({ enum: FuelOrderStatus })
  @Column({ type: pgEnum('fuel_order_status'), default: FuelOrderStatus.DRAFT })
  status!: FuelOrderStatus;

  @ApiProperty({ nullable: true })
  @Column({ name: 'ordered_at', type: 'timestamptz', nullable: true })
  orderedAt!: Date | null;

  @ApiProperty()
  @Column({ name: 'expected_delivery_at', type: 'timestamptz' })
  expectedDeliveryAt!: Date;

  @ApiProperty({ nullable: true })
  @Column({ type: 'text', nullable: true })
  notes!: string | null;

  @ApiProperty({ nullable: true })
  @Column({ name: 'created_by', type: 'uuid', nullable: true })
  createdBy!: string | null;

  @ApiProperty({ nullable: true })
  @Column({ name: 'cancelled_at', type: 'timestamptz', nullable: true })
  cancelledAt!: Date | null;

  @ApiProperty({ nullable: true })
  @Column({ name: 'cancellation_reason', type: 'text', nullable: true })
  cancellationReason!: string | null;

  @ManyToOne(() => Business, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'business_id' })
  business!: Business;

  @ManyToOne(() => Supplier, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'supplier_id' })
  supplier!: Supplier;

  @ManyToOne(() => Branch, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'destination_branch_id' })
  destinationBranch!: Branch;

  @ManyToOne(() => User, { onDelete: 'SET NULL', nullable: true })
  @JoinColumn({ name: 'created_by' })
  creator!: User | null;

  @OneToMany(() => FuelOrderItem, (item) => item.fuelOrder, { cascade: true })
  items!: FuelOrderItem[];

  /** One order may be fulfilled by many tankers (docs/09 §11). */
  @OneToMany(() => Delivery, (delivery) => delivery.fuelOrder)
  deliveries!: Delivery[];
}
